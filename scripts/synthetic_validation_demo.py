"""Exercise the sequential scoring harness with fictional, simulated outputs.

This does not run LLMs or measure medical accuracy. Answer keys remain outside
the temporary workspaces created for each case/arm.
"""

import json
from pathlib import Path
import tempfile

from validation.harness import ARMS, SequentialSuite


def main():
    root = Path(tempfile.mkdtemp(prefix="synthetic-validation-"))
    root.chmod(0o700)
    inputs = root / "operator-inputs"
    sealed = root / "operator-sealed-answers"
    inputs.mkdir()
    sealed.mkdir()
    (inputs / "fictional-901.txt").write_text("Invented presentation one. No reference diagnosis included.")
    (inputs / "fictional-902.txt").write_text("Invented presentation two. No reference diagnosis included.")
    manifest = inputs / "manifest.json"
    manifest.write_text(json.dumps({"schema_version": 1, "kind": "synthetic", "cases": [
        {"case_id": "SYNTH-901", "input_file": "fictional-901.txt"},
        {"case_id": "SYNTH-902", "input_file": "fictional-902.txt"},
    ]}))
    (sealed / "SYNTH-901.json").write_text(json.dumps({"case_id": "SYNTH-901",
                                                   "accepted_ids": ["INVENTED-CONDITION-A"],
                                                   "critical_flags": ["INVENTED-ALERT-A"]}))
    (sealed / "SYNTH-902.json").write_text(json.dumps({"case_id": "SYNTH-902",
                                                   "accepted_ids": ["INVENTED-CONDITION-B"],
                                                   "critical_flags": []}))
    suite = SequentialSuite(manifest, sealed, root / "isolated-agent-work", root / "operator-results")
    for case_id in ("SYNTH-901", "SYNTH-902"):
        for arm in ARMS:
            active = suite.prepare_next()
            assert (active["case_id"], active["arm"]) == (case_id, arm)
            # Simulated outputs are fixed fixtures, not generated by a model or read from sealed answer files.
            guesses = (["INVENTED-CONDITION-A"] if case_id == "SYNTH-901" and arm == "team"
                       else ["INVENTED-CONDITION-B"] if case_id == "SYNTH-902" and arm == "opus"
                       else ["UNRELATED-INVENTED-CODE"])
            output = root / "operator-submission.json"
            output.write_text(json.dumps({"case_id": case_id, "arm": arm,
                                          "diagnoses": guesses,
                                          "critical_flags": ["INVENTED-ALERT-A"] if arm == "team" else []}))
            suite.submit(output)
    report = suite.score()
    print("Synthetic evaluation root:", root)
    print("Arms scored sequentially:", len(report["scores"]))
    print("Clinical validation:", report["clinical_validation"])
    print("Scoring output:", root / "operator-results/score.json")


if __name__ == "__main__":
    main()
